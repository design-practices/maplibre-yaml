const require = createRequire(import.meta.url);

/**
 * Regenerate agent-facing assets (hosted JSON Schemas, llms.txt, llms-full.txt)
 * on every dev start and production build, from the core schemas + example
 * configs — so they can never go stale relative to the docs they ship with.
 */
const agentAssets = {
  name: "maplibre-yaml-agent-assets",
  hooks: {
    "astro:config:setup": () => {
      generateAgentAssets();
    },
  },
};

/**
 * Compile the launch page's classics (/classics/) with `mlym emit
 * --with-fallbacks` on every dev start and build, into
 * public/classics/<name>/ejected/ (git-ignored). The page's ejected panes
 * run exactly that output in vanilla maplibre-gl, so they can never be a
 * hand-copy; docs/test/classics-eject.test.mjs pins them byte-for-byte to
 * a fresh emit. Same precedent as the agent assets above.
 */
const classicsEject = {
  name: "maplibre-yaml-classics-eject",
  hooks: {
    "astro:config:setup": () => {
      generateClassicsEject();
    },
  },
};

/**
 * Regenerate the YAML reference (src/content/docs/reference/yaml/, git-ignored)
 * from the core Zod schemas on every dev start and build, so it can never
 * drift from the validator. The generator imports the schemas' TypeScript
 * source, so it runs as a tsx subprocess rather than inside the config loader.
 * Must run before Starlight so the sidebar's autogenerated group sees the pages.
 */
const yamlReference = {
  name: "maplibre-yaml-yaml-reference",
  hooks: {
    "astro:config:setup": () => {
      execFileSync(
        process.execPath,
        [
          require.resolve("tsx/cli"),
          fileURLToPath(new URL("./scripts/generate-yaml-reference.ts", import.meta.url)),
        ],
        { stdio: "inherit" },
      );
    },
  },
};

/**
 * The core package's public entry points (its package.json `exports`), each
 * with the module name its file header declares (`@module ...`). Drives both
 * the TypeDoc run and the sidebar, so the two cannot disagree.
 */
